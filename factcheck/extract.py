#!/usr/bin/env python3
"""Turn the manuscript and the Modern Alchemy companion into Prolog facts.

Writes factcheck/generated/*.pl. Nothing here judges anything: it only states,
as facts, what the text says. The judging is in checks.pl.

    generated/text.pl       every sentence of both editions, with features
    generated/glossary.pl   the 119 companion concepts
    generated/notation.pl   the worked chains, as relations
    generated/refs.pl       the reference list in book/19
    generated/anchors.pl    whether each hand-written claim's quote is still in the text
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FC = ROOT / "factcheck"
GEN = FC / "generated"
EDITIONS = {"book": ROOT / "book", "book-hs": ROOT / "book-hs"}
SKIP_CHAPTERS = {("book", 18)}          # the index of terms makes no assertions

# ----------------------------------------------------------------- prolog output


def s(text: str) -> str:
    """Prolog double-quoted string."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def a(text: str) -> str:
    """Prolog quoted atom."""
    return "'" + str(text).replace("\\", "\\\\").replace("'", "\\'") + "'"


DISCONTIGUOUS = "sentence/6, number/3, year/2, keywords/2, certainty_word/2, hedged/1, xref/2, cites/3, " \
                "heading_count/6, section_box/5, chapter/4, chain/6, chain_cycles/1, arc_step/3, concept/5, substrate_rank/2, ref/6, anchor/2"


def write(name: str, header: str, lines: list[str]) -> None:
    GEN.mkdir(parents=True, exist_ok=True)
    body = "\n".join(lines)
    (GEN / name).write_text(f"% GENERATED by factcheck/extract.py — do not edit.\n% {header}\n"
                            f":- discontiguous {DISCONTIGUOUS}.\n\n{body}\n", encoding="utf-8")


def norm_ws(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def plain(md: str) -> str:
    md = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", md)
    md = md.replace("**", "").replace("`", "")
    md = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"\1", md)
    return norm_ws(md)


# ------------------------------------------------------------------- numbers

UNITS_WORDS = {"zero": 0, "one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6, "seven": 7, "eight": 8,
               "nine": 9, "ten": 10, "eleven": 11, "twelve": 12, "thirteen": 13, "fourteen": 14, "fifteen": 15,
               "sixteen": 16, "seventeen": 17, "eighteen": 18, "nineteen": 19}
TENS_WORDS = {"twenty": 20, "thirty": 30, "forty": 40, "fifty": 50, "sixty": 60, "seventy": 70, "eighty": 80, "ninety": 90}
SCALES = {"hundred": 100, "thousand": 1_000, "million": 1_000_000, "billion": 1_000_000_000, "trillion": 1_000_000_000_000}
_W = "|".join(list(UNITS_WORDS) + list(TENS_WORDS))
NUMWORD = re.compile(
    r"\b(?:(?:%s)(?:-(?:%s))?|(?:a\s+)?hundred)(?![a-z])"       # forty, forty-two, a hundred
    r"(?:[ -](?:hundred|thousand|million|billion|trillion)(?![a-z]))*"     # … thousand
    r"(?:\s+and\s+(?:a half|(?:%s)(?:-(?:%s))?)(?![a-z]))?"      # … and a half / hundred and five
    % (_W, "|".join(UNITS_WORDS), _W, "|".join(UNITS_WORDS)),
    re.I,
)
DIGITS = re.compile(r"(?<![\w.\-/])(\d{1,3}(?:,\d{3})+|\d+(?:\.\d+)?)(?:\s+(million|billion|trillion|thousand|hundred))?(?![\w])")
STOP = set("""a an the of and or to in on at by for with from as is are was were be been being it its this that these
those which who whom whose what when where why how than then there their they them he she his her we our you your i
not no nor but if so such into over under about after before between through during without within more most less
least very much many some any each every all both either neither other another same own only also just even still
per around roughly nearly almost approximately""".split())
UNIT_SKIP = {"of", "per", "or", "and", "to", "a", "the", "more", "than", "times", "fewer", "about", "around", "roughly", "nearly"}


def words_to_number(phrase: str) -> float | None:
    total, current, half = 0, 0, False
    for w in re.split(r"[ -]+", phrase.lower()):
        if w in ("and", "a"):
            continue
        if w == "half":
            half = True
            continue
        if w in UNITS_WORDS:
            current += UNITS_WORDS[w]
        elif w in TENS_WORDS:
            current += TENS_WORDS[w]
        elif w == "hundred":
            current = (current or 1) * 100
        elif w in SCALES:
            total += (current or 1) * SCALES[w]
            current = 0
        else:
            return None
    value = total + current
    return value + 0.5 if half else value


def singular(w: str) -> str:
    w = w.lower().strip(".,;:()\"'—–")
    for a_, b_ in (("metres", "metre"), ("meters", "metre"), ("meter", "metre"), ("ies", "y")):
        if w.endswith(a_) and len(w) > len(a_) + 1:
            return w[: -len(a_)] + b_
    if w.endswith("s") and not w.endswith("ss") and len(w) > 3:
        return w[:-1]
    return w


def unit_after(text: str, end: int) -> str:
    for w in re.findall(r"[A-Za-z][A-Za-z\-]*", text[end:end + 60])[:3]:
        if w.lower() not in UNIT_SKIP and w.lower() not in STOP:
            return singular(w)
    return "none"


def numbers_in(text: str) -> list[tuple[float, str, str]]:
    """(value, unit, kind) with kind in {number, year}. Chapter references are not quantities."""
    out: list[tuple[float, str, str]] = []
    taken: list[tuple[int, int]] = [m.span() for m in XREF.finditer(text)]
    for m in DIGITS.finditer(text):
        if any(lo <= m.start() < hi for lo, hi in taken):
            continue
        raw, scale = m.group(1), m.group(2)
        val = float(raw.replace(",", ""))
        if scale:
            val *= SCALES[scale.lower()]
        tail = text[m.end():m.end() + 6]
        bce = bool(re.match(r"\s*BCE", tail))
        is_year = (not scale and "," not in raw and "." not in raw and 1000 <= val <= 2030
                   and not re.match(r"\s*(?:years?|metres?|m\b|km|%)", text[m.end():m.end() + 8]))
        if bce or (re.match(r"\s*(?:–|-)\s*\d{3,4}\s*BCE", tail + text[m.end() + 6:m.end() + 20]) and val < 10000):
            out.append((-val, "year", "year"))
        elif is_year:
            out.append((val, "year", "year"))
        else:
            out.append((val, unit_after(text, m.end()), "number"))
        taken.append(m.span())
    for m in NUMWORD.finditer(text):
        if any(lo <= m.start() < hi for lo, hi in taken):
            continue
        phrase = m.group(0)
        val = words_to_number(phrase)
        if re.search(r"\band\b", phrase) and not re.search(r"hundred|a half", phrase, re.I):
            continue                                 # "one and two" is two numbers, not three
        if val is None or (val == 1 and not re.search(r"hundred|thousand|million|billion", phrase, re.I)):
            continue
        out.append((val, unit_after(text, m.end()), "number"))
    return out


# --------------------------------------------------------------------- words

CERTAIN = re.compile(r"\b(always|never|proves?|proven|certainly|definitely|undoubtedly|impossible|inevitabl[ey]|"
                     r"must have|cannot be|no doubt|beyond doubt|conclusively)\b", re.I)
HEDGE = re.compile(r"\b(may|might|perhaps|possibly|probably|suggests?|appears?|seems?|likely|plausibl[ey]|"
                   r"contested|disputed|argued|unclear|unknown|proposal|proposed)\b", re.I)
XREF = re.compile(r"\bchapters?\s+(\d{1,2})((?:\s*(?:,|and|or|through|to|–|-)\s*\d{1,2})*)", re.I)


def keywords(text: str) -> list[str]:
    ws = {singular(w) for w in re.findall(r"[A-Za-z][A-Za-z\-]{4,}", text)}
    return sorted(w for w in ws if w not in STOP and len(w) >= 5)


# ------------------------------------------------------------------ the text


def chapters(ed: str):
    for f in sorted(EDITIONS[ed].glob("[0-9][0-9]-*.md")):
        yield int(f.name[:2]), f


def paragraphs(md: str):
    """Yield (line, kind, tier, heading_path, text). Tier from explicit markers only."""
    md = re.sub(r"<!--.*?-->", lambda m: "\n" * m.group(0).count("\n"), md, flags=re.S)
    lines = md.splitlines()
    i, heading, author_section = 0, "", False
    section_tier, section_level, heading_level = None, 0, 0
    while i < len(lines):
        line = lines[i]
        if not line.strip():
            i += 1
            continue
        if line.strip() == "## References":
            return
        m = re.match(r"^(#{1,6})\s+(.*)", line)
        if m:
            heading = m.group(2).strip()
            heading_level = len(m.group(1))
            author_section = False
            if section_tier and heading_level <= section_level:
                section_tier = None
            yield i + 1, f"h{len(m.group(1))}", "unmarked", heading, heading
            i += 1
            continue
        j = i
        while j < len(lines) and lines[j].strip() and not re.match(r"^#{1,6}\s", lines[j]):
            j += 1
        block = lines[i:j]
        text = " ".join(l.strip() for l in block)
        tier = "unmarked"
        if block[0].startswith(">"):
            inner = re.sub(r"^>\s?", "", text.replace("\n", " "))
            inner = re.sub(r"\s>\s?", " ", inner)
            if re.match(r"\*\*Settled\.\*\*", inner):
                tier = "settled"
            elif re.match(r"\*\*Still argued about\.\*\*", inner):
                tier = "contested"
            elif re.match(r"\*\*My own idea\.\*\*", inner):
                tier = "author"
            text = inner
            kind = "quote"
            if tier != "unmarked" and re.search(r"\bEverything in this section\b", inner):
                section_tier, section_level = tier, heading_level
                yield i + 1, "section_box", tier, heading, inner
        elif block[0].lstrip().startswith("|"):
            kind = "table"
        elif re.match(r"^\s*([-*]|\d+\.)\s", block[0]):
            kind = "list"
        else:
            kind = "p"
        if re.match(r"^\*What follows is the author's", text):     # "reading", "own rant", ...
            author_section = True
        if re.match(r"^\*(?:Here the author would go further|A comment from the author)", text) or author_section:
            tier = "author"
        if tier == "unmarked" and section_tier:
            tier = section_tier
        yield i + 1, kind, tier, heading, text
        i = j


def split_sentences(text: str) -> list[str]:
    parts = re.split(r"(?<=[.!?])[\"”’)]?\s+(?=[A-Z0-9*\"“(])", text)
    return [p.strip() for p in parts if len(p.split()) >= 3]


def extract_text(refs: list[dict]) -> tuple[list[str], dict]:
    facts: list[str] = []
    stats = {"sentences": 0, "numeric": 0}
    surnames = sorted({n for r in refs for n in r["authors"] if len(n) >= 4}, key=len, reverse=True)
    counters: dict[tuple[str, int], int] = {}
    for ed in EDITIONS:
        for num, f in chapters(ed):
            if (ed, num) in SKIP_CHAPTERS:
                continue
            md = f.read_text(encoding="utf-8")
            title = re.search(r"^#\s+(.*)$", md, re.M)
            facts.append(f"chapter({a(ed)}, {num}, {s(f.name)}, {s(title.group(1) if title else f.stem)}).")
            k = counters.get((ed, num), 0)       # chapter 0 is two files; ids must not restart
            in_section: list[tuple[str, int, int, int]] = []    # heading counts
            current_h = None
            for line, kind, tier, heading, text in paragraphs(md):
                if kind == "section_box":
                    facts.append(f"section_box({a(ed)}, {num}, {line}, {a(tier)}, {s(heading)}).")
                    continue
                if kind.startswith("h"):
                    level = int(kind[1])
                    m = re.match(r"^(Two|Three|Four|Five|Six|Seven|Eight|Nine|Ten)\b", heading)
                    current_h = [heading, {"two": 2, "three": 3, "four": 4, "five": 5, "six": 6, "seven": 7, "eight": 8,
                                           "nine": 9, "ten": 10}[m.group(1).lower()], 0, line, level] if m else None
                    if m:
                        in_section.append(current_h)
                    continue
                if current_h and (kind == "p" and text.startswith("**") or kind == "list" and "**" in text):
                    current_h[2] += text.count("\n- **") + 1 if kind == "list" else 1
                if kind == "table":
                    continue
                for sent in split_sentences(plain(text)):
                    k += 1
                    sid = f"s_{ed.replace('-', '')}_{num:02d}_{k:04d}"
                    stats["sentences"] += 1
                    facts.append(f"sentence({sid}, {a(ed)}, {num}, {line}, {a(tier)}, {s(sent)}).")
                    nums = numbers_in(sent)
                    for val, unit, kind_ in nums:
                        facts.append(f"{'year' if kind_ == 'year' else 'number'}({sid}, {val:g}{'' if kind_ == 'year' else ', ' + a(unit)}).")
                    if nums:
                        stats["numeric"] += 1
                        facts.append(f"keywords({sid}, [{', '.join(a(w) for w in keywords(sent))}]).")
                    for m in CERTAIN.finditer(sent):
                        facts.append(f"certainty_word({sid}, {a(m.group(1).lower())}).")
                    if HEDGE.search(sent):
                        facts.append(f"hedged({sid}).")
                    for m in XREF.finditer(sent):
                        ns = [int(m.group(1))] + [int(x) for x in re.findall(r"\d{1,2}", m.group(2) or "")]
                        for n in ns:
                            facts.append(f"xref({sid}, {n}).")
                    masked: list[tuple[int, int]] = []
                    for name in surnames:
                        for nm in re.finditer(r"\b" + re.escape(name) + r"\b(?!\s+[A-Z][a-z])", sent):
                            if any(lo <= nm.start() < hi for lo, hi in masked):
                                continue
                            masked.append(nm.span())
                            y = re.search(r"\b(1[5-9]\d\d|20[0-2]\d)\b", sent[nm.end():nm.end() + 45])
                            if y and not re.search(r"\b(1[5-9]\d\d|20[0-2]\d)\b", sent[nm.end():nm.end() + y.start()]):
                                facts.append(f"cites({sid}, {a(name)}, {y.group(1)}).")
            counters[(ed, num)] = k
            for heading, stated, found, line, _ in in_section:
                facts.append(f"heading_count({a(ed)}, {num}, {line}, {s(heading)}, {stated}, {found}).")
    return facts, stats


# ------------------------------------------------------------ the companion

TIER_ORDER = {"PH": 1, "CH": 2, "PL": 3, "BI": 4, "MC": 5}      # substrate tiers; CO, CX, MF cut across


def extract_glossary() -> tuple[list[str], dict[str, str]]:
    facts, sym2id = [], {}
    for line in (ROOT / "modern_alchemy" / "01-glossary.md").read_text(encoding="utf-8").splitlines():
        m = re.match(r"^\|\s*([A-Z]{2})-(\d{2})\s*\|\s*([^|]+?)\s*\|\s*`([^`]+)`\s*\|\s*([^|]+?)\s*\|", line)
        if m:
            cid = f"{m.group(1)}-{m.group(2)}"
            sym2id[m.group(4)] = cid
            facts.append(f"concept({a(cid)}, {s(m.group(3))}, {a(m.group(4))}, {a(m.group(1).lower())}, {s(m.group(5))}).")
    for t, r in TIER_ORDER.items():
        facts.append(f"substrate_rank({a(t.lower())}, {r}).")
    return facts, sym2id


OPS = {"→": "produces", "⊂": "kind_of", "↑": "amplifies", "↓": "constrains", "≈": "analogous", "↺": "cycles", "⊕": "interacts", "∥": "parallel"}


def extract_notation() -> list[str]:
    facts: list[str] = []
    text = (ROOT / "modern_alchemy" / "02-notation.md").read_text(encoding="utf-8")
    section, n, arc_n = "", 0, 0
    in_block = False
    for line in text.splitlines():
        if line.startswith("### "):
            section = line[4:].strip()
        if line.startswith("```"):
            in_block = not in_block
            continue
        if not in_block or section in ("",) or "Templates" in section:
            continue
        # The gloss is the first run of two or more spaces followed by a lowercase word;
        # symbols always start uppercase, and formulas are padded for alignment.
        m = re.match(r"^(?:[A-Za-z]+\s*:\s+)?(.*?)(?:\s{2,}([a-z].*))?$", line.strip())
        formula, gloss = m.group(1), (m.group(2) or "")
        if not formula.strip():
            continue
        n += 1
        syms = lambda part: [x for x in re.findall(r"[A-Za-z]+", part)]
        if section == "The whole arc":
            # Every line here is a strand of the arc. A strand with a single arrow would
            # otherwise be read as a worked chain, and so support its own step. Steps are
            # numbered across strands.
            steps = [p.strip() for p in formula.split("→")]
            for x, y in zip(steps, steps[1:]):
                arc_n += 1
                facts.append(f"arc_step({arc_n}, {a(x)}, {a(y)}).")
            continue
        op = next((o for o in ("→", "≈", "⊂", "↑", "↓") if o in formula), None)
        if not op:
            continue
        left, right = formula.split(op, 1)
        cyc = "↺" in left
        lhs = syms(left.replace("↺", "+"))
        rhs = syms(right)
        rel = OPS[op]
        facts.append(f"chain({n}, {s(section)}, {rel}, [{', '.join(a(x) for x in dict.fromkeys(lhs))}], [{', '.join(a(x) for x in rhs)}], {s(gloss or '')}).")
        if cyc:
            facts.append(f"chain_cycles({n}).")
    return facts


# ------------------------------------------------------------- references


def extract_refs() -> list[dict]:
    md = (ROOT / "book" / "19-references-and-models.md").read_text(encoding="utf-8")
    md = md.split("## References", 1)[1]
    refs = []
    for line in md.splitlines():
        m = re.match(r"^- (.+?) \((\d{4})(?:/(\d{4}))?\)\. (.+) \*Chs?\. ([\d, ]+)\.\*$", line)
        if not m:
            continue
        authors_raw = m.group(1)
        # Capitals include accented Latin ones, so "Dilly, É." keeps Dilly as first author.
        names = re.findall(r"(?:^|, |& )([A-ZÀ-ÖØ-Þ][\w’'\-]+(?: [A-ZÀ-ÖØ-Þ][\w’'\-]+)?(?: [a-z]+ [A-Z][\w\-]+)?), (?:[A-ZÀ-ÖØ-Þ]\.|[A-ZÀ-ÖØ-Þ][a-z]?\.)", authors_raw)
        if not names:
            names = [authors_raw.split(",")[0].rstrip(".")]
        names = [re.sub(r"^(von|van|v\.)\s+", "", x) for x in names]
        years = [int(m.group(2))] + ([int(m.group(3))] if m.group(3) else [])
        refs.append({"first": names[0], "authors": names, "years": years,
                     "chapters": [int(c) for c in re.findall(r"\d+", m.group(5))], "dagger": "†" in line})
    return refs


def ref_facts(refs: list[dict]) -> list[str]:
    out = []
    for i, r in enumerate(refs, 1):
        for y in r["years"]:
            out.append(f"ref(r{i}, {a(r['first'])}, {y}, [{', '.join(a(x) for x in r['authors'])}], [{', '.join(map(str, r['chapters']))}], {'dagger' if r['dagger'] else 'checked'}).")
    return out


# ---------------------------------------------------------------- anchors


CLAIM = re.compile(r"^claim\(\s*(\w+)\s*,\s*'?([\w-]+)'?\s*,\s*(\d+)\s*,\s*\"((?:[^\"\\]|\\.)*)\"", re.M)


def claim_files() -> list[Path]:
    return [FC / "claims.pl"] + sorted((FC / "claims").glob("*.pl"))


def chapter_texts() -> dict[tuple[str, int], str]:
    texts = {}
    for ed in EDITIONS:
        for num, f in chapters(ed):
            text = norm_ws(plain(re.sub(r"<!--.*?-->", "", f.read_text(encoding="utf-8"), flags=re.S)))
            texts[(ed, num)] = (texts[(ed, num)] + " " + text) if (ed, num) in texts else text   # chapter 0 is two files
    return texts


def quotes_in(path: Path, texts: dict) -> list[tuple[str, str, int, str, bool]]:
    out = []
    for m in CLAIM.finditer(path.read_text(encoding="utf-8")):
        cid, ed, num, quote = m.group(1), m.group(2), int(m.group(3)), m.group(4).replace('\\"', '"')
        out.append((cid, ed, num, quote, norm_ws(plain(quote)) in texts.get((ed, num), "")))
    return out


def extract_anchors() -> list[str]:
    """For each claim/6 in claims.pl and claims/*.pl, record whether its quote is still in its chapter."""
    texts = chapter_texts()
    return [f"anchor({cid}, {'present' if ok else 'missing'})."
            for f in claim_files() for cid, _, _, _, ok in quotes_in(f, texts)]


def check_quotes(files: list[str]) -> int:
    """Read-only: report claims whose quote is not in their chapter. Writes nothing."""
    texts, bad, n = chapter_texts(), 0, 0
    for f in files:
        for cid, ed, num, quote, ok in quotes_in(Path(f), texts):
            n += 1
            if not ok:
                bad += 1
                print(f"MISSING {cid} ({ed} ch.{num}): {quote[:120]}")
    print(f"{n} claims checked, {bad} quotes not found")
    return 1 if bad else 0


def uncovered(specs: list[str]) -> int:
    """Read-only: list number- or date-bearing sentences no claim covers yet.
    Specs look like book:0-5 or book-hs:10-13. A sentence counts as covered when
    the first 40 characters of some claim's quote appear in it (as in checks.pl)."""
    texts = chapter_texts()
    prefixes = {(ed, num): [] for ed, num in texts}
    for f in claim_files():
        for _, ed, num, quote, _ in quotes_in(f, texts):
            prefixes.setdefault((ed, num), []).append(norm_ws(plain(quote))[:40])
    total = 0
    for spec in specs:
        ed, _, rng = spec.partition(":")
        lo, _, hi = rng.partition("-")
        for num, f in chapters(ed):
            if not (int(lo) <= num <= int(hi or lo)) or (ed, num) in SKIP_CHAPTERS:
                continue
            for line, kind, _, _, text in paragraphs(f.read_text(encoding="utf-8")):
                if kind.startswith("h") or kind in ("table", "section_box"):
                    continue
                for sent in split_sentences(plain(text)):
                    if numbers_in(sent) and not any(p_ in sent for p_ in prefixes.get((ed, num), [])):
                        total += 1
                        print(f"{ed} ch.{num} line {line}: {sent}")
    print(f"-- {total} uncovered number- or date-bearing sentences")
    return 0


def main() -> int:
    if sys.argv[1:2] == ["--check-quotes"]:
        return check_quotes(sys.argv[2:])
    if sys.argv[1:2] == ["--uncovered"]:
        return uncovered(sys.argv[2:])
    refs = extract_refs()
    text_facts, stats = extract_text(refs)
    gloss, _ = extract_glossary()
    write("text.pl", f"{stats['sentences']} sentences, {stats['numeric']} with numbers or years", text_facts)
    write("glossary.pl", "modern_alchemy/01-glossary.md", gloss)
    write("notation.pl", "modern_alchemy/02-notation.md", extract_notation())
    write("refs.pl", f"{len(refs)} entries from book/19", ref_facts(refs))
    write("anchors.pl", "claims.pl quotes checked against the text", extract_anchors())
    print(f"extracted {stats['sentences']} sentences ({stats['numeric']} with numbers), {len(gloss)} glossary facts, {len(refs)} references")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
