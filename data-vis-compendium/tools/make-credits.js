// Writes CREDITS.md and credits.html from the content: every stored picture and every embedded
// video, with who made it, its licence, and where it came from. Run: node tools/make-credits.js
// (tests fail if either file is out of step with content/stops.js). credits.html exists because
// GitHub Pages turns a linked .md file into .html, which would break a link to CREDITS.md.
const fs = require("node:fs");
const path = require("node:path");

const plain = (s) => String(s).replace(/\*/g, "");

// The credits, grouped by stop: [{ heading, items: [{ kind, where, ...fields }] }]
function creditGroups(entries) {
  const groups = [];
  for (const e of entries) {
    if (e.kind !== "stop") continue;
    const items = [];
    const visit = (where, visuals) => {
      for (const v of visuals || []) {
        const pics = v.type === "picture" ? [v.picture] : v.type === "gallery" ? v.pictures : [];
        for (const p of pics) items.push({ kind: "picture", where, src: p.src, alt: plain(p.alt), creator: p.creator, licence: p.licence, url: p.sourceUrl, ours: !!p.ours });
        if (v.type === "video" && v.video.id) items.push({ kind: "video", where, ...v.video });
        if (v.type === "sim" && v.opts && v.opts.clips) {
          for (const c of Object.values(v.opts.clips)) if (c && c.id) items.push({ kind: "video", where: where || "under the slider", ...c });
        }
      }
    };
    visit("", e.visuals);
    for (const r of e.sideRoads || []) visit(`side road: ${plain(r.title)}`, r.visuals);
    if (items.length) groups.push({ heading: `${e.number} · ${plain(e.title)}`, items });
  }
  return groups;
}

const INTRO = [
  "Everything below is used under its own licence. Pictures marked “the compendium's own” are ours (CC BY-SA 4.0); the rest were made by others. Our own text and data are CC BY-SA 4.0; our code is GPL-3.0 (see the folder's README).",
  "Pictures are stored in `assets/`, scaled down, with their metadata removed. Videos are not stored: they are embedded from YouTube (privacy-enhanced mode) and load only when a reader presses play.",
];
const watch = (id) => `https://www.youtube.com/watch?v=${id}`;
// Our own pictures say so in place of a licence; the intro gives their licence (CC BY-SA 4.0).
const OURS = "the compendium's own";

function creditsText(entries) {
  const lines = ["# Credits", "", INTRO[0], "", INTRO[1], ""];
  for (const g of creditGroups(entries)) {
    lines.push(`## ${g.heading}`, "");
    for (const i of g.items) {
      const where = i.where ? ` (${i.where})` : "";
      if (i.kind === "picture") lines.push(`- \`${i.src}\`: ${i.alt}. ${i.creator}, ${i.ours ? OURS : i.licence}. ${i.url}${where}`);
      else lines.push(`- Video: “${i.title}”, ${i.channel}. ${watch(i.id)}${where}`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

function creditsHtml(entries) {
  const NKC = globalThis.NKC;
  const esc = NKC.esc;
  const link = (url, text) => `<a href="${esc(url)}">${esc(text)}</a>`;
  const body = creditGroups(entries).map((g) => {
    const items = g.items.map((i) => {
      const where = i.where ? ` <span class="where">(${esc(i.where)})</span>` : "";
      if (i.kind === "picture") {
        const deed = NKC.licenceUrl(i.licence);
        const licence = i.ours ? esc(OURS) : deed ? link(deed, i.licence) : esc(i.licence);
        return `<li><code>${esc(i.src)}</code>: ${esc(i.alt)}. ${esc(i.creator)}, ${licence}. ${link(i.url, "Source")}.${where}</li>`;
      }
      return `<li>Video: “${esc(i.title)}”, ${esc(i.channel)}. ${link(watch(i.id), "Watch on YouTube")}.${where}</li>`;
    }).join("\n      ");
    return `    <h2>${esc(g.heading)}</h2>\n    <ul>\n      ${items}\n    </ul>`;
  }).join("\n");
  const intro = INTRO.map((p) => `    <p>${esc(p).replace(/`([^`]+)`/g, "<code>$1</code>")}</p>`).join("\n");
  return `<!DOCTYPE html>
<!-- SPDX-License-Identifier: CC-BY-SA-4.0 -->
<!-- Generated by tools/make-credits.js from content/stops.js; do not edit by hand. -->
<html lang="en-GB">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Credits: Natural Knowledge, a visual compendium</title>
  <link rel="stylesheet" href="css/style.css">
</head>
<body>
  <main class="credits-page">
    <p><a href="index.html">← Back to the compendium</a></p>
    <h1>Credits</h1>
${intro}
${body}
  </main>
</body>
</html>
`;
}

module.exports = { creditsText, creditsHtml };

if (require.main === module) {
  require("../js/core.js");
  require("../js/media.js");
  require("../content/pictures.js");
  const NKC = require("../content/stops.js");
  const dir = path.join(__dirname, "..");
  fs.writeFileSync(path.join(dir, "CREDITS.md"), creditsText(NKC.ENTRIES));
  fs.writeFileSync(path.join(dir, "credits.html"), creditsHtml(NKC.ENTRIES));
  console.log("wrote CREDITS.md and credits.html");
}
